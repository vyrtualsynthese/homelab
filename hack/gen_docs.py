"""Render the documentation pages that can be derived from this repository.

Two pages are generated, never hand-edited: `docs/reference/routes.md` from the charts' rendered
`IngressRoute` objects, and `docs/backup/coverage.md` from the backup chart's values. Both are
committed, because GitHub and every agent read the repository and not the rendered site.

    hack/gen_docs.py --check              every page matches its source
    hack/gen_docs.py --write              regenerate and write
    hack/gen_docs.py --write --only routes
    hack/gen_docs.py --check --only coverage

Exit: 0 in agreement, 1 a page differs or a chart could not be rendered.
"""

from __future__ import annotations

import argparse
import dataclasses
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

import yaml

from check_exposure import PUBLIC_HOSTS

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED_MARKER = "<!-- generated by hack/gen_docs.py; do not edit -->"
HOST_RE = re.compile(r"Host\(`([^`]+)`\)")
REDIRECT = "redirect-to-https"


class GenError(Exception):
    """A chart could not be rendered: setup problem, not a difference."""


@dataclasses.dataclass(frozen=True)
class Route:
    host: str
    app: str
    namespace: str
    entrypoints: tuple[str, ...]
    middlewares: tuple[str, ...]
    tls: str
    public: bool


def _middleware_name(reference: str) -> str:
    name = reference.split("@", 1)[0]
    return name.removeprefix("kube-system-")


def _tls_label(spec: dict, host: str, entrypoints: tuple[str, ...]) -> str:
    """What answers the handshake: nothing on a `web`-only route, else the name's certificate."""
    if "websecure" not in entrypoints:
        return "none"
    tls = spec.get("tls") or {}
    if tls.get("secretName") or tls.get("certResolver"):
        return "Let's Encrypt"
    if host.endswith(".kub.local"):
        return "internal CA"
    if host.endswith(".ashudev.com") or host.endswith(".ashuvidz.com"):
        return "Let's Encrypt"
    return "store (SNI)"


def parse_rendered_routes(documents: str, app: str, namespace: str) -> list[Route]:
    """One Route per rendered IngressRoute document that matches at least one host."""
    routes: list[Route] = []
    for doc in yaml.safe_load_all(documents):
        if not isinstance(doc, dict) or doc.get("kind") != "IngressRoute":
            continue
        spec = doc.get("spec") or {}
        host = None
        middlewares: list[str] = []
        for rule in spec.get("routes") or []:
            match = HOST_RE.search(rule.get("match") or "")
            if match and host is None:
                host = match.group(1)
            for reference in rule.get("middlewares") or []:
                name = _middleware_name(reference.get("name", ""))
                if name and name not in middlewares:
                    middlewares.append(name)
        if host is None:
            continue
        routes.append(
            Route(
                host=host,
                app=app,
                namespace=namespace,
                entrypoints=tuple(spec.get("entryPoints") or ()),
                middlewares=tuple(middlewares),
                tls=_tls_label(spec, host, tuple(spec.get("entryPoints") or ())),
                public=host in PUBLIC_HOSTS,
            )
        )
    return routes


def _first_line(text: str) -> str:
    for line in text.splitlines():
        if line.strip():
            return line.strip()
    return "no output"


def _chart_label(chart_dir: pathlib.Path) -> str:
    """The chart's own name, so a temporary copy reports the chart a reader can find."""
    try:
        metadata = yaml.safe_load((chart_dir / "Chart.yaml").read_text(encoding="utf-8")) or {}
    except yaml.YAMLError:
        return chart_dir.name
    return str(metadata.get("name") or chart_dir.name)


def render_chart(chart_dir: pathlib.Path) -> str:
    """Render one chart, building its dependencies in a temporary copy when they are not vendored."""
    chart_yaml = chart_dir / "Chart.yaml"
    work = chart_dir
    temporary: pathlib.Path | None = None
    if "dependencies:" in chart_yaml.read_text(encoding="utf-8") and not (chart_dir / "charts").is_dir():
        temporary = pathlib.Path(tempfile.mkdtemp(prefix="gen-docs-"))
        work = temporary / chart_dir.name
        shutil.copytree(chart_dir, work)
        built = subprocess.run(
            ["helm", "dependency", "build", str(work)], capture_output=True, text=True
        )
        if built.returncode != 0:
            shutil.rmtree(temporary, ignore_errors=True)
            raise GenError(
                f"{_chart_label(chart_dir)}: helm dependency build failed: {_first_line(built.stderr)}"
            )
    try:
        rendered = subprocess.run(
            ["helm", "template", "doc", str(work), "-f", str(chart_dir / "values.yaml")],
            capture_output=True,
            text=True,
        )
    finally:
        if temporary is not None:
            shutil.rmtree(temporary, ignore_errors=True)
    if rendered.returncode != 0:
        raise GenError(f"{_chart_label(chart_dir)}: helm template failed: {_first_line(rendered.stderr)}")
    return rendered.stdout


def applications(root: pathlib.Path) -> dict[str, tuple[str, pathlib.Path]]:
    """ArgoCD Application name -> (destination namespace, chart directory relative to root)."""
    found: dict[str, tuple[str, pathlib.Path]] = {}
    for path in sorted((root / "cluster" / "argocd" / "projects").rglob("*.yaml")):
        try:
            doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict) or doc.get("kind") != "Application":
            continue
        spec = doc.get("spec") or {}
        namespace = (spec.get("destination") or {}).get("namespace") or "-"
        paths = []
        if (spec.get("source") or {}).get("path"):
            paths.append(spec["source"]["path"])
        for source in spec.get("sources") or []:
            if source.get("path"):
                paths.append(source["path"])
        chart = next((p for p in paths if str(p).startswith("cluster/helm/")), None)
        if chart is None:
            continue
        found[path.stem] = (namespace, pathlib.Path(chart))
    return found


def _is_redirect(route: Route) -> bool:
    return route.entrypoints == ("web",) and REDIRECT in route.middlewares


def _table(routes: list[Route]) -> list[str]:
    lines = [
        "| Host | Application | Namespace | Gate | TLS | Public? |",
        "|---|---|---|---|---|---|",
    ]
    for route in sorted(routes, key=lambda r: (r.host, r.app)):
        gate = ", ".join(f"`{name}`" for name in route.middlewares) or "none"
        public = "yes" if route.public else "no"
        lines.append(
            f"| `{route.host}` | {route.app} | `{route.namespace}` | {gate} | {route.tls} | {public} |"
        )
    return lines


def _declares_a_route(chart_dir: pathlib.Path) -> bool:
    """True when the chart's own templates or values can render an IngressRoute.

    A chart may carry its routes in `values.yaml` under `extraObjects` instead of a
    template of its own; ArgoCD does exactly that.
    """
    candidates = list((chart_dir / "templates").glob("*.y*ml")) if (chart_dir / "templates").is_dir() else []
    candidates += list(chart_dir.glob("values*.y*ml"))
    return any("IngressRoute" in p.read_text(encoding="utf-8") for p in candidates)


def _merge_hosts(routes: list[Route]) -> list[Route]:
    """One row per hostname: a host's `web` and `websecure` routers are the same entry."""
    grouped: dict[tuple[str, str], list[Route]] = {}
    for route in routes:
        grouped.setdefault((route.host, route.app), []).append(route)
    merged: list[Route] = []
    for (host, app), rows in sorted(grouped.items()):
        primary = next((r for r in rows if "websecure" in r.entrypoints), rows[0])
        middlewares: list[str] = []
        for row in [primary, *rows]:
            for name in row.middlewares:
                if name not in middlewares:
                    middlewares.append(name)
        entrypoints: list[str] = []
        for row in rows:
            for name in row.entrypoints:
                if name not in entrypoints:
                    entrypoints.append(name)
        merged.append(
            dataclasses.replace(
                primary,
                entrypoints=tuple(entrypoints),
                middlewares=tuple(middlewares),
            )
        )
    return merged


def render_routes(root: pathlib.Path) -> str:
    """The routes page, rendered from every chart that declares a route."""
    routes: list[Route] = []
    apps: set[str] = set()
    for name, (namespace, chart_rel) in sorted(applications(root).items()):
        chart_dir = root / chart_rel
        if not (chart_dir / "Chart.yaml").is_file():
            continue  # a values-only directory: pattern B, no templates of its own
        if not _declares_a_route(chart_dir):
            continue
        rendered = parse_rendered_routes(render_chart(chart_dir), name, namespace)
        if rendered:
            apps.add(name)
        routes.extend(rendered)
    routes = _merge_hosts(routes)

    public = [r for r in routes if r.public]
    plain = [r for r in routes if not r.public and r.tls == "none"]
    internal_tls = [r for r in routes if not r.public and r.tls != "none"]

    lines = [
        GENERATED_MARKER,
        "",
        "# Routes: every hostname, its gate and its certificate",
        "",
        f"> **Generated page.** {len(routes)} hostnames, rendered from the charts of {len(apps)}",
        "> Applications by `hack/gen_docs.py`. Do not edit it: the tables are the charts.",
        "",
        "Regenerate: `python3 hack/gen_docs.py --write --only routes`",
        "",
        "Hostnames, middlewares and TLS options are rendered from the `IngressRoute` objects each chart",
        "declares. A host with a `web` and a `websecure` router is one row, and its gate names both.",
        "A route that no Application owns is not here: the Traefik dashboard is a Helm release value, and",
        "it is named in [network.md](../how-it-works/network.md).",
        "How a request arrives, what the gate does and which certificate answers the handshake are",
        "[how it works](../how-it-works/network.md); who signs in where is",
        "[the SSO matrix](sso-applications.md). `Public?` is what",
        "[`hack/check_exposure.py`](../../hack/check_exposure.py) allows.",
        "",
        f"## Public ({len(public)})",
        "",
        "On the allowlist, meant to answer the internet.",
        "",
        *_table(public),
        "",
        f"## Internal over TLS ({len(internal_tls)})",
        "",
        *_table(internal_tls),
        "",
        f"## Internal without TLS ({len(plain)})",
        "",
        *_table(plain),
        "",
        "## Sources",
        "",
        "- `cluster/argocd/projects/**/*.yaml` — which chart serves which namespace",
        "- every `cluster/helm/**/templates/*.yaml` that declares an `IngressRoute`, and a chart's",
        "  `values.yaml` when it carries one as an `extraObjects` entry",
        "- `hack/check_exposure.py` — the public allowlist",
        "",
    ]
    return "\n".join(lines)


PAGES: dict[str, tuple[str, object]] = {
    "reference/routes.md": ("routes", render_routes),
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the pages")
    parser.add_argument("--check", action="store_true", help="fail when a page differs from its source")
    parser.add_argument("--only", help="one page, by its label (routes) or its path (reference/routes.md)")
    args = parser.parse_args(argv)
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")
    labels = {label: page for page, (label, _) in PAGES.items()}
    if args.only is None:
        targets = sorted(PAGES)
    elif args.only in PAGES:
        targets = [args.only]
    elif args.only in labels:
        targets = [labels[args.only]]
    else:
        parser.error(f"unknown page: {args.only} (known: {', '.join(sorted(labels))})")
    result = 0
    for page in targets:
        _, renderer = PAGES[page]
        try:
            content = renderer(ROOT)
        except GenError as exc:
            print(f"gen-docs: {exc}", file=sys.stderr)
            return 1
        path = ROOT / "docs" / page
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            continue
        existing = path.read_text(encoding="utf-8") if path.is_file() else ""
        if content != existing:
            print(f"would change: docs/{page}")
            result = 1
    return result


if __name__ == "__main__":
    sys.exit(main())
