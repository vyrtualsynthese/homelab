"""Render the documentation pages that can be derived from this repository.

The routes page is generated from the charts' rendered `IngressRoute` objects; the backup coverage
page follows from the backup chart's values. Both are committed, because GitHub and every agent read
the repository and not the rendered site.

    hack/gen_docs.py --check              every page matches its source
    hack/gen_docs.py --write              regenerate and write
    hack/gen_docs.py --write --only routes
    hack/gen_docs.py --check --only coverage

Exit: 0 in agreement, 1 a page differs or a chart could not be rendered.
"""

from __future__ import annotations

import argparse
import dataclasses
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

import yaml

from check_exposure import PUBLIC_HOSTS

ROOT = pathlib.Path(__file__).resolve().parents[1]
GENERATED_MARKER = "<!-- generated by hack/gen_docs.py; do not edit -->"
HOST_RE = re.compile(r"Host\(`([^`]+)`\)")
REDIRECT = "redirect-to-https"
# `IngressRoute` objects live in the cluster, read on 2026-11-25 through the read-only MCP
# ServiceAccount and written down with that date in cluster/helm/security/security-exporter/
# values.yaml. The rendered side is counted, not typed in; this side cannot be, and the page
# carries no date of its own, so the date lives in the values file.
LIVE_INGRESS_ROUTES = 73


class GenError(Exception):
    """A chart could not be rendered: setup problem, not a difference."""


@dataclasses.dataclass(frozen=True)
class Route:
    host: str
    app: str
    namespace: str
    entrypoints: tuple[str, ...]
    middlewares: tuple[str, ...]
    tls: str
    public: bool


def _middleware_name(reference: str) -> str:
    name = reference.split("@", 1)[0]
    return name.removeprefix("kube-system-")


def _tls_label(spec: dict, host: str, entrypoints: tuple[str, ...]) -> str:
    """What answers the handshake: nothing on a `web`-only route, else the name's certificate."""
    if "websecure" not in entrypoints:
        return "none"
    tls = spec.get("tls") or {}
    if tls.get("secretName") or tls.get("certResolver"):
        return "Let's Encrypt"
    if host.endswith(".kub.local"):
        return "internal CA"
    if host.endswith(".ashudev.com") or host.endswith(".ashuvidz.com"):
        return "Let's Encrypt"
    return "store (SNI)"


def parse_rendered_routes(documents: str, app: str, namespace: str) -> list[Route]:
    """One Route per rendered IngressRoute document that matches at least one host."""
    routes: list[Route] = []
    for doc in yaml.safe_load_all(documents):
        if not isinstance(doc, dict) or doc.get("kind") != "IngressRoute":
            continue
        spec = doc.get("spec") or {}
        entrypoints = tuple(spec.get("entryPoints") or ())
        by_host: dict[str, list[str]] = {}
        for rule in spec.get("routes") or []:
            match = HOST_RE.search(rule.get("match") or "")
            if not match:
                continue
            middlewares = by_host.setdefault(match.group(1), [])
            for reference in rule.get("middlewares") or []:
                name = _middleware_name(reference.get("name", ""))
                if name and name not in middlewares:
                    middlewares.append(name)
        for host, middlewares in by_host.items():
            routes.append(
                Route(
                    host=host,
                    app=app,
                    namespace=namespace,
                    entrypoints=entrypoints,
                    middlewares=tuple(middlewares),
                    tls=_tls_label(spec, host, entrypoints),
                    public=host in PUBLIC_HOSTS,
                )
            )
    return routes


def _ingress_kind_counts(documents: str) -> tuple[int, int]:
    """Objects a chart renders: those that are `IngressRoute`, and those of any `Ingress` kind.

    The second is what `hack/check-exposure.sh` counts, which is why it is larger: its grep is
    `^kind: Ingress`, so an `IngressClass` or an `IngressRouteTCP` lands in the same total.
    """
    kinds = [
        doc.get("kind") for doc in yaml.safe_load_all(documents) if isinstance(doc, dict)
    ]
    return (
        sum(1 for kind in kinds if kind == "IngressRoute"),
        sum(1 for kind in kinds if isinstance(kind, str) and kind.startswith("Ingress")),
    )


def _first_line(text: str) -> str:
    for line in text.splitlines():
        if line.strip():
            return line.strip()
    return "no output"


def _chart_label(chart_dir: pathlib.Path) -> str:
    """The chart's own name, so a temporary copy reports the chart a reader can find."""
    try:
        metadata = yaml.safe_load((chart_dir / "Chart.yaml").read_text(encoding="utf-8")) or {}
    except yaml.YAMLError:
        return chart_dir.name
    return str(metadata.get("name") or chart_dir.name)


def render_chart(chart_dir: pathlib.Path) -> str:
    """Render one chart, building its dependencies in a temporary copy when they are not vendored."""
    chart_yaml = chart_dir / "Chart.yaml"
    work = chart_dir
    temporary: pathlib.Path | None = None
    if "dependencies:" in chart_yaml.read_text(encoding="utf-8") and not (chart_dir / "charts").is_dir():
        temporary = pathlib.Path(tempfile.mkdtemp(prefix="gen-docs-"))
        work = temporary / chart_dir.name
        shutil.copytree(chart_dir, work)
        built = subprocess.run(
            ["helm", "dependency", "build", str(work)], capture_output=True, text=True
        )
        if built.returncode != 0:
            shutil.rmtree(temporary, ignore_errors=True)
            raise GenError(
                f"{_chart_label(chart_dir)}: helm dependency build failed: {_first_line(built.stderr)}"
            )
    try:
        rendered = subprocess.run(
            ["helm", "template", "doc", str(work), "-f", str(chart_dir / "values.yaml")],
            capture_output=True,
            text=True,
        )
    finally:
        if temporary is not None:
            shutil.rmtree(temporary, ignore_errors=True)
    if rendered.returncode != 0:
        raise GenError(f"{_chart_label(chart_dir)}: helm template failed: {_first_line(rendered.stderr)}")
    return rendered.stdout


def applications(root: pathlib.Path) -> dict[str, tuple[str, pathlib.Path]]:
    """ArgoCD Application name -> (destination namespace, chart directory relative to root)."""
    found: dict[str, tuple[str, pathlib.Path]] = {}
    for path in sorted((root / "cluster" / "argocd" / "projects").rglob("*.yaml")):
        try:
            doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict) or doc.get("kind") != "Application":
            continue
        spec = doc.get("spec") or {}
        namespace = (spec.get("destination") or {}).get("namespace") or "-"
        paths = []
        if (spec.get("source") or {}).get("path"):
            paths.append(spec["source"]["path"])
        for source in spec.get("sources") or []:
            if source.get("path"):
                paths.append(source["path"])
        chart = next((p for p in paths if str(p).startswith("cluster/helm/")), None)
        if chart is None:
            continue
        name = str((doc.get("metadata") or {}).get("name") or path.stem)
        found[name] = (namespace, pathlib.Path(chart))
    return found


def applications_without_a_chart(root: pathlib.Path) -> list[str]:
    """Applications whose source is not a chart in `cluster/helm/`, named so the page can say so."""
    missing: list[str] = []
    for path in sorted((root / "cluster" / "argocd" / "projects").rglob("*.yaml")):
        try:
            doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if not isinstance(doc, dict) or doc.get("kind") != "Application":
            continue
        spec = doc.get("spec") or {}
        paths = []
        if (spec.get("source") or {}).get("path"):
            paths.append(spec["source"]["path"])
        for source in spec.get("sources") or []:
            if source.get("path"):
                paths.append(source["path"])
        if not any(str(p).startswith("cluster/helm/") for p in paths):
            missing.append(str((doc.get("metadata") or {}).get("name") or path.stem))
    return missing


def _table(routes: list[Route]) -> list[str]:
    lines = [
        "| Host | Application | Namespace | Gate | TLS | Public? |",
        "|---|---|---|---|---|---|",
    ]
    for route in sorted(routes, key=lambda r: (r.host, r.app)):
        gate = ", ".join(f"`{name}`" for name in route.middlewares) or "none"
        public = "yes" if route.public else "no"
        lines.append(
            f"| `{route.host}` | {route.app} | `{route.namespace}` | {gate} | {route.tls} | {public} |"
        )
    return lines


def _declares_a_route(chart_dir: pathlib.Path) -> bool:
    """True when the chart's own templates or values can render an IngressRoute.

    A chart may carry its routes in `values.yaml` under `extraObjects` instead of a
    template of its own; ArgoCD does exactly that. A values file can also declare a
    route without naming the kind at all: see `_declares_a_dashboard_route`.
    """
    candidates = list((chart_dir / "templates").glob("*.y*ml")) if (chart_dir / "templates").is_dir() else []
    candidates += list(chart_dir.glob("values*.y*ml"))
    if any("IngressRoute" in p.read_text(encoding="utf-8") for p in candidates):
        return True
    for path in chart_dir.glob("values*.y*ml"):
        try:
            values = yaml.safe_load(path.read_text(encoding="utf-8"))
        except yaml.YAMLError:
            continue
        if _declares_a_dashboard_route(values):
            return True
    return False


def _declares_a_dashboard_route(values) -> bool:
    """True when a values tree carries the Traefik chart's dashboard block, switched on.

    The upstream chart renders its dashboard IngressRoute from values rather than a template whose
    text names it, so a wrapper that carries the block declares a route without saying so. The
    chart's own default is `enabled: false`, and a block that keeps it renders nothing.
    """
    if not isinstance(values, dict):
        return False
    dashboard = (values.get("ingressRoute") or {}).get("dashboard")
    found = isinstance(dashboard, dict) and dashboard.get("enabled") is True
    return found or any(_declares_a_dashboard_route(value) for value in values.values())


def _merge_hosts(routes: list[Route]) -> list[Route]:
    """One row per hostname: a host's `web` and `websecure` routers are the same entry."""
    grouped: dict[tuple[str, str], list[Route]] = {}
    for route in routes:
        grouped.setdefault((route.host, route.app), []).append(route)
    merged: list[Route] = []
    for (host, app), rows in sorted(grouped.items()):
        primary = next((r for r in rows if "websecure" in r.entrypoints), rows[0])
        middlewares: list[str] = []
        for row in [primary, *rows]:
            for name in row.middlewares:
                if name not in middlewares:
                    middlewares.append(name)
        entrypoints: list[str] = []
        for row in rows:
            for name in row.entrypoints:
                if name not in entrypoints:
                    entrypoints.append(name)
        merged.append(
            dataclasses.replace(
                primary,
                entrypoints=tuple(entrypoints),
                middlewares=tuple(middlewares),
            )
        )
    return merged


def render_routes(root: pathlib.Path) -> str:
    """The routes page, rendered from every chart that declares a route."""
    routes: list[Route] = []
    objects = 0
    ingress_objects = 0
    apps: set[str] = set()
    for name, (namespace, chart_rel) in sorted(applications(root).items()):
        chart_dir = root / chart_rel
        if not (chart_dir / "Chart.yaml").is_file():
            # A values-only directory (pattern B) is consumed by a remote chart, so its routes would
            # have to come from `extraObjects`; one that does is a chart this page cannot see.
            if _declares_a_route(chart_dir):
                raise GenError(
                    f"{chart_rel}: {name} declares an IngressRoute but holds no Chart.yaml to render"
                )
            continue
        if not _declares_a_route(chart_dir):
            continue
        manifest = render_chart(chart_dir)
        chart_objects, chart_ingress = _ingress_kind_counts(manifest)
        objects += chart_objects
        ingress_objects += chart_ingress
        rendered = parse_rendered_routes(manifest, name, namespace)
        if rendered:
            apps.add(name)
        routes.extend(rendered)
    routes = _merge_hosts(routes)

    public = [r for r in routes if r.public]
    plain = [r for r in routes if not r.public and r.tls == "none"]
    internal_tls = [r for r in routes if not r.public and r.tls != "none"]

    lines = [
        GENERATED_MARKER,
        "",
        "# Routes: every hostname, its gate and its certificate",
        "",
        f"> **Generated page.** {len(routes)} hostnames, rendered from the charts of {len(apps)}",
        "> Applications by `hack/gen_docs.py`. Do not edit it: the tables are the charts.",
        "",
        "Regenerate: `python3 hack/gen_docs.py --write --only routes`",
        "",
        "Hostnames, middlewares and TLS options are rendered from the `IngressRoute` objects each chart",
        "declares. A host with a `web` and a `websecure` router is one row, and its gate names both.",
        "The dashboard is the one host whose `web` router is applied by hand rather than rendered:",
        "`traefik.kub.local` on port 80 is redirected by",
        "`cluster/infrastructure/traefik/dashboard/redirect.yaml`, and that twin merges into the row",
        "the chart-rendered `websecure` router gives the host. That twin is also the whole difference",
        f"between what the cluster holds and what these charts render: {LIVE_INGRESS_ROUTES} `IngressRoute`",
        f"objects live against the {objects} rendered here, and `kube-system/traefik-dashboard-redirect`",
        "is the only name on one side and not the other. `cluster/infrastructure/**` is applied by hand,",
        "so no Application can ever render it, and the gap is a shape of this repository rather than",
        "drift. The other three ways a router goes missing are empty here: every Application's `path`",
        "holds a chart, no Application is a leftover of a retired app, and every router a chart renders",
        "is live. Both counts, with the day the live one was read, are in",
        "`cluster/helm/security/security-exporter/values.yaml`. One internal route is an API rather",
        "than a page: `loki.kub.local` serves Loki's query API and its query frontend, and the logs are",
        "read in Grafana. The `IngressRouteTCP` and `IngressRouteUDP` entries Syncthing and Minecraft",
        "declare match on `HostSNI(*)`, carry no hostname, and are therefore not rows here — which is",
        f"why `hack/check-exposure.sh` prints `checked: {ingress_objects} routes`: its grep takes",
        "`IngressClass` and those four objects as well, and none of them is an `IngressRoute`.",
        "How a request arrives, what the gate does and which certificate answers the handshake are",
        "[how it works](../how-it-works/network.md); who signs in where is",
        "[the SSO matrix](sso-applications.md). `Public?` is what `hack/check_exposure.py` allows.",
        "",
        f"## Public ({len(public)})",
        "",
        "On the allowlist, meant to answer the internet.",
        "",
        *_table(public),
        "",
        f"## Internal over TLS ({len(internal_tls)})",
        "",
        *_table(internal_tls),
        "",
        f"## Internal without TLS ({len(plain)})",
        "",
        *_table(plain),
        "",
        "## Sources",
        "",
        "- `cluster/argocd/projects/**/*.yaml` — which chart serves which namespace",
        "- every `cluster/helm/**/templates/*.yaml` that declares an `IngressRoute`, and a chart's",
        "  `values.yaml` when it carries one as an `extraObjects` entry",
        "- `hack/check_exposure.py` — the public allowlist",
        "",
    ]
    without_a_chart = applications_without_a_chart(root)
    if without_a_chart:
        lines += [
            "## Applications this table cannot see",
            "",
            "Their source is not a chart under `cluster/helm/`, so there is no `helm template` to read:",
            "",
            *[f"- `{name}`" for name in without_a_chart],
            "",
        ]
    return "\n".join(lines)


@dataclasses.dataclass(frozen=True)
class CoverageRow:
    stream: str
    schedule: str
    node: str
    claim: str
    namespace: str
    kind: str


def coverage_rows(values: dict) -> list[CoverageRow]:
    """One row per backed-up claim and per NFS export, straight from the matrix."""
    rows: list[CoverageRow] = []
    for node, config in sorted((values.get("nodes") or {}).items()):
        config = config or {}
        for claim in config.get("claims") or []:
            rows.append(
                CoverageRow(
                    stream=f"nodes-{node}",
                    schedule=str(config.get("schedule") or "-"),
                    node=node,
                    claim=str(claim.get("claim") or "-"),
                    namespace=str(claim.get("namespace") or "-"),
                    kind=str(claim.get("kind") or "files"),
                )
            )
    nfs = values.get("nfs") or {}
    for path in nfs.get("paths") or []:
        rows.append(
            CoverageRow(
                stream="nfs",
                schedule=str(nfs.get("schedule") or "-"),
                node="nfs",
                claim=str(path.get("tag") or "-"),
                namespace="-",
                kind="files",
            )
        )
    return rows


def render_coverage(root: pathlib.Path) -> str:
    """The coverage matrix, rendered from the backup chart's values."""
    source = root / "cluster" / "helm" / "backup" / "values.yaml"
    values = yaml.safe_load(source.read_text(encoding="utf-8")) or {}
    rows = coverage_rows(values)
    streams = [row.stream for row in rows]
    order: list[str] = []
    for name in (values.get("streams") or []):
        if name.get("name") in streams and name["name"] not in order:
            order.append(name["name"])
    for name in streams:
        if name not in order:
            order.append(name)

    lines = [
        GENERATED_MARKER,
        "",
        "# What is backed up, and where",
        "",
        f"> **Generated page.** {len(rows)} rows over {len(order)} streams, rendered from",
        "> `cluster/helm/backup/values.yaml` by `hack/gen_docs.py`. Do not edit it: the matrix is the",
        "> values file.",
        "",
        "Regenerate: `python3 hack/gen_docs.py --write --only coverage`",
        "",
        "One row per claim and per export. `Schedule` is the CronJob's time in the node's local",
        "timezone; `Kind` is `sqlite` when the row stages a database through SQLite's backup API and",
        "`files` when the directory is copied as it is. A stream with no rows is a stream that backs up",
        "nothing, which is a defect rather than a quiet night: the verifier fails it.",
        "",
    ]
    for stream in order:
        group = [row for row in rows if row.stream == stream]
        if not group:
            continue
        lines += [
            f"## `{stream}` — {group[0].schedule}",
            "",
            "| Claim or tag | Namespace | Node | Kind |",
            "|---|---|---|---|",
        ]
        for row in group:
            lines.append(f"| `{row.claim}` | `{row.namespace}` | {row.node} | {row.kind} |")
        lines.append("")
    lines += [
        "## Sources",
        "",
        "- `cluster/helm/backup/values.yaml` — the matrix, and the measured size beside each row",
        "- `cluster/helm/backup/templates/` — the six CronJobs that read it",
        "",
        "What is deliberately absent — the media libraries, the music, the books, the downloads — is",
        "absent by decision and named in [what a loss costs](what-a-loss-costs.md).",
        "",
    ]
    return "\n".join(lines)


PAGES: dict[str, tuple[str, object]] = {
    "reference/routes.md": ("routes", render_routes),
    "backup/coverage.md": ("coverage", render_coverage),
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write the pages")
    parser.add_argument("--check", action="store_true", help="fail when a page differs from its source")
    parser.add_argument("--only", help="one page, by its label (routes) or its path (reference/routes.md)")
    args = parser.parse_args(argv)
    if not (args.write or args.check):
        parser.error("one of --write or --check is required")
    labels = {label: page for page, (label, _) in PAGES.items()}
    if args.only is None:
        targets = sorted(PAGES)
    elif args.only in PAGES:
        targets = [args.only]
    elif args.only in labels:
        targets = [labels[args.only]]
    else:
        parser.error(f"unknown page: {args.only} (known: {', '.join(sorted(labels))})")
    result = 0
    for page in targets:
        _, renderer = PAGES[page]
        try:
            content = renderer(ROOT)
        except GenError as exc:
            print(f"gen-docs: {exc}", file=sys.stderr)
            return 1
        path = ROOT / "docs" / page
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            continue
        existing = path.read_text(encoding="utf-8") if path.is_file() else ""
        if content != existing:
            print(f"would change: docs/{page}")
            result = 1
    return result


if __name__ == "__main__":
    sys.exit(main())
